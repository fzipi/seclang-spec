"""Generate formal/RESULTS.md, the published results of the Lean model.

Usage: uv run python tools/formal_results.py --crs /path/to/coreruleset [--differential formal/.lake/differential.json] [--check]
Runs the three executables under formal/ (built already: `cd formal && lake build`) on the
unit corpora, the engine profiles and an OWASP CRS checkout, scans the Lean sources for
theorems and `#guard` checks, and writes formal/RESULTS.md; `--check` only compares and
exits 1 when the file is stale (the Lean CI job runs it). The site renders the file.
"""
import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools import crs_rules, engine_rules, validate  # noqa: E402

FORMAL = validate.ROOT / "formal"
OUT = FORMAL / "RESULTS.md"


@dataclass
class CheckSummary:
    files: int = 0
    passed: int = 0
    failed: int = 0
    skipped_cases: int = 0
    skipped_files: list = field(default_factory=list)


@dataclass
class EvalSummary:
    stages: int = 0
    mismatches: int = 0
    unsupported: list = field(default_factory=list)


def parse_check(text: str) -> CheckSummary:
    s = CheckSummary()
    for line in text.splitlines():
        m = re.match(r"^(\S+): (\d+) passed, (\d+) failed(?:, (\d+) skipped)?$", line)
        if m:
            s.files += 1
            s.passed += int(m[2])
            s.failed += int(m[3])
            s.skipped_cases += int(m[4] or 0)
            continue
        m = re.match(r"^(\S+): skipped \(not formalized\)$", line)
        if m:
            s.skipped_files.append(m[1])
    return s


def parse_eval(text: str) -> EvalSummary:
    s = EvalSummary()
    for line in text.splitlines():
        m = re.match(r"^(\S+): unsupported \((.*)\)$", line)
        if m:
            s.unsupported.append((m[1], m[2]))
        m = re.match(r"^(\d+) stages, (\d+) mismatches, (\d+) unsupported profiles$", line)
        if m:
            s.stages, s.mismatches = int(m[1]), int(m[2])
    return s


def count_guards(text: str) -> int:
    return sum(1 for line in text.splitlines() if line.startswith("#guard"))


def theorems(text: str) -> list[tuple[str, str]]:
    out = []
    # the docstring may not contain `-/`, or the match would run from an earlier comment
    for m in re.finditer(r"/--\s*((?:(?!-/).)*?)\s*-/\s*theorem\s+(\w+)", text, re.S):
        out.append((m[2], " ".join(m[1].split())))
    return out


def check_cell(s: CheckSummary, skipped_reason: str) -> str:
    cell = f"{s.files} files: {s.passed} cases passed, {s.failed} failed"
    if s.skipped_cases:
        cell += f", {s.skipped_cases} skipped ({skipped_reason})"
    if s.skipped_files:
        cell += "; not formalized: " + ", ".join(f"`{f}`" for f in s.skipped_files)
    return cell


def render(*, transformations: CheckSummary, operators: CheckSummary, parse: str, eval_: EvalSummary,
           crs: tuple[str, str], guards: list[tuple[str, int]], thms: list[tuple[str, str]],
           differential: EvalSummary | None = None, crs_differential: EvalSummary | None = None) -> str:
    lines = [
        "# Formal model results",
        "",
        "Generated by `tools/formal_results.py` from the Lean executables in `formal/`; the Lean CI",
        "job regenerates this file and fails when it is stale. The model is a reference, not an",
        "engine: a mismatch is a defect to fix before merge, never a known gap.",
        "",
        "## Corpus and profiles",
        "",
        "| Run | Input | Result |",
        "|---|---|---|",
        f"| `seclang-check` | `tests/unit/transformations` | {check_cell(transformations, 'outside the model')} |",
        f"| `seclang-check` | `tests/unit/operators` | {check_cell(operators, 'regex outside the Core subset, ADR-0018')} |",
        f"| `seclang-parse` | `tests/engine` | {parse} |",
        f"| `seclang-eval` | `tests/engine` | {eval_.stages} stages, {eval_.mismatches} mismatches, {len(eval_.unsupported)} unsupported profiles |",
        f"| `seclang-parse` | OWASP CRS (`crs_setup_version` {crs[0]}) | {crs[1]} |",
        *([f"| `seclang-eval` | generated requests, what Coraza did (`adapters/coraza/cmd/differential`, seed 1, 30 per profile) | {differential.stages} stages, {differential.mismatches} mismatches |"] if differential else []),
        *([f"| `seclang-eval` | OWASP CRS with generated requests, what Coraza did (`tools/crs_profile.py`, seed 1) | {crs_differential.stages} stages, {crs_differential.mismatches} mismatches |"] if crs_differential else []),
        "",
        "## Profiles outside the model",
        "",
        "Reported as unsupported with the reason; the list is the model's boundary, not a gap.",
        "",
        "| Profile | Reason |",
        "|---|---|",
        *[f"| `{p}` | {why} |" for p, why in eval_.unsupported],
        "",
        "## Theorems",
        "",
        "Proved over the model: `formal/SecLang/Regex.lean` (ADR-0027) and",
        "`formal/SecLang/Semantics.lean` (processing model, ADR-0016, ADR-0017, ADR-0028, ADR-0029, body limits).",
        "",
        "| Theorem | Statement |",
        "|---|---|",
        *[f"| `{n}` | {d} |" for n, d in thms],
        "",
        "## Compile-time checks",
        "",
        "`#guard` assertions evaluated by every `lake build`.",
        "",
        "| Module | Checks |",
        "|---|---|",
        *[f"| `formal/SecLang/{m}` | {n} |" for m, n in guards],
        f"| **Total** | **{sum(n for _, n in guards)}** |",
        "",
    ]
    return "\n".join(lines)


def run(args: list[str], cwd: Path) -> str:
    return subprocess.run(args, cwd=cwd, text=True, capture_output=True, check=False).stdout


def generate(crs_dir: Path, differential_file: Path | None = None, crs_differential_file: Path | None = None) -> str:
    lake = FORMAL / ".lake"
    lake.mkdir(exist_ok=True)
    (lake / "engine-rules.json").write_text(json.dumps(engine_rules.extract(validate.ROOT)), encoding="utf-8")
    (lake / "crs.json").write_text(json.dumps(crs_rules.extract(crs_dir)), encoding="utf-8")
    transformations = parse_check(run(["lake", "exe", "seclang-check"], FORMAL))
    operators = parse_check(run(["lake", "exe", "seclang-check", "../tests/unit/operators"], FORMAL))
    parse = run(["lake", "exe", "seclang-parse", ".lake/engine-rules.json"], FORMAL).strip().splitlines()[-1]
    eval_ = parse_eval(run(["lake", "exe", "seclang-eval", ".lake/engine-rules.json"], FORMAL))
    crs_line = run(["lake", "exe", "seclang-parse", ".lake/crs.json"], FORMAL).strip().splitlines()[-1]
    setup = (crs_dir / "crs-setup.conf.example").read_text(encoding="utf-8")
    m = re.search(r"crs_setup_version=(\d+)", setup)
    guards = [(p.name, count_guards(p.read_text(encoding="utf-8"))) for p in sorted((FORMAL / "SecLang").glob("*.lean"))]
    guards = [(n, c) for n, c in guards if c]
    thms = [t for p in sorted((FORMAL / "SecLang").glob("*.lean")) for t in theorems(p.read_text(encoding="utf-8"))]
    differential = parse_eval(run(["lake", "exe", "seclang-eval", str(differential_file.resolve())], FORMAL)) if differential_file else None
    crs_differential = parse_eval(run(["lake", "exe", "seclang-eval", str(crs_differential_file.resolve())], FORMAL)) if crs_differential_file else None
    return render(transformations=transformations, operators=operators, parse=parse, eval_=eval_,
                  crs=(m[1] if m else "unknown", crs_line), guards=guards, thms=thms, differential=differential,
                  crs_differential=crs_differential)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--crs", required=True, type=Path, help="OWASP CRS checkout")
    ap.add_argument("--check", action="store_true", help="exit 1 when formal/RESULTS.md is stale")
    ap.add_argument("--differential", type=Path, help="JSON written by adapters/coraza/cmd/differential (seed 1, 30 per profile)")
    ap.add_argument("--crs-differential", type=Path, help="the same for the CRS profile of tools/crs_profile.py (seed 1, 20 requests)")
    a = ap.parse_args()
    text = generate(a.crs, a.differential, a.crs_differential)
    if a.check:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit("formal/RESULTS.md is stale: run `uv run python tools/formal_results.py --crs <dir>`")
        print("formal/RESULTS.md is fresh")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(validate.ROOT)}")
